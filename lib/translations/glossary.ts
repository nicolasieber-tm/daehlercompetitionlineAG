/** Glossar als Textblock für den Systemprompt. */
export function glossaryPromptBlock(): string {
  const keep = KEEP_AS_IS.map((k) => `- ${k}`).join("\n");
  const pairs = GLOSSARY.map(([de, en]) => `- ${de} -> ${en}`).join("\n");
  return `Unverändert übernehmen (nie übersetzen):\n${keep}\n\nGlossar (immer so übersetzen):\n${pairs}`;
}
